// Generate facts from ICU's Chinese calendar (same calendar as the design).
// Regeneration requires Node with ICU 77.1; committed output needs no Node to build.
import { writeFileSync } from 'node:fs';
const fmt = new Intl.DateTimeFormat('en-u-ca-chinese', {
  year:'numeric',month:'numeric',day:'numeric',timeZone:'UTC'
});
const rows=[];
for(let t=Date.UTC(1999,0,1);t<=Date.UTC(2101,0,1);t+=86400000) {
  const parts=Object.fromEntries(fmt.formatToParts(t).map(p=>[p.type,p.value]));
  if(parts.day==='1') rows.push(`  {${t/86400000},${parts.relatedYear},${parseInt(parts.month)},${parts.month.includes('bis') ? 'true':'false'}},`);
}
writeFileSync(new URL('../include/lunar_data.h',import.meta.url),
  `// Generated by tools/generate_lunar.mjs using ICU ${process.versions.icu}. Civil days, lunar month starts.\n#pragma once\nstruct LunarStart { int day; int16_t year; uint8_t month; bool leap; };\nstatic const LunarStart LUNAR_STARTS[]={\n${rows.join('\n')}\n};\n`);
